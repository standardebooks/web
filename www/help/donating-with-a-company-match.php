		<p>Your employer may offer to match your charitable donations, helping your contribution to Standard Ebooks go further. We accept matching gifts via <a href="https://www.fracturedatlas.org">Fractured Atlas</a>, our 501(c)(3) fiscal sponsor.</p>
		<section id="requesting-a-match">
			<h2>Making a donation with a match<a class="heading-permalink" href="#requesting-a-match" aria-label="Permalink"></a></h2>
			<ul>
				<li>
					<p>Ask your employer how to request a matching gift.</p>
				</li>
				<li>
					<p>Select Fractured Atlas as the recipient, and specify Standard Ebooks as the purpose or designation. <strong>Matching gifts must be payable to Fractured Atlas.</strong></p>
				</li>
				<li>
					<p>Send any forms requiring the charity’s confirmation to Fractured Atlas for completion, rather than to Standard Ebooks. For online programs, <a href="https://www.fracturedatlas.org/get-in-touch">send Fractured Atlas the verification link</a> or submit your information through the employer’s portal so it can contact Fractured Atlas.</p>
				</li>
			</ul>
			<p>After the paperwork is submitted, it can take some months for Fractured Atlas to receive and process the gift.</p>
		</section>
		<section id="benevity">
			<h2>Using Benevity to match a donation<a class="heading-permalink" href="#benevity" aria-label="Permalink"></a></h2>
			<p>If your employer uses Benevity (also called the American Online Giving Foundation), select Fractured Atlas as the nonprofit and enter Standard Ebooks in the special purpose or designation field. Omitting the project name can delay your donation.</p>
			<p>It can take some months Fractured Atlas to receive and process your matching gift. Some employers hold the original donation until they can send it together with the match.</p>
