CREATE TABLE IF NOT EXISTS `Ebooks` (
  `EbookId` int(10) unsigned NOT NULL AUTO_INCREMENT,
  `Identifier` varchar(511) NOT NULL,
  `WwwFilesystemPath` varchar(511) DEFAULT NULL,
  `RepoFilesystemPath` varchar(511) DEFAULT NULL,
  `KindleCoverUrl` varchar(511) DEFAULT NULL,
  `EpubUrl` varchar(511) DEFAULT NULL,
  `AdvancedEpubUrl` varchar(511) DEFAULT NULL,
  `KepubUrl` varchar(511) DEFAULT NULL,
  `Azw3Url` varchar(511) DEFAULT NULL,
  `DistCoverUrl` varchar(511) DEFAULT NULL,
  `Title` varchar(255) NOT NULL,
  `FullTitle` varchar(255) DEFAULT NULL,
  `AlternateTitle` varchar(255) DEFAULT NULL,
  `ShortTitle` varchar(255) DEFAULT NULL,
  `Abstract` text DEFAULT NULL,
  `Description` text DEFAULT NULL,
  `Language` varchar(10) DEFAULT NULL,
  `WordCount` int(10) unsigned DEFAULT NULL,
  `ReadingEase` float DEFAULT NULL,
  `GitHubUrl` varchar(255) DEFAULT NULL,
  `WikipediaUrl` varchar(255) DEFAULT NULL,
  `EbookCreatedAt` datetime DEFAULT NULL,
  `EbookUpdatedAt` datetime DEFAULT NULL,
  `TextSinglePageByteCount` bigint(20) unsigned DEFAULT NULL,
  `DownloadsPast30Days` int(10) unsigned NOT NULL DEFAULT 0,
  `DownloadsTotal` int(10) unsigned NOT NULL DEFAULT 0,
  `IsPatronSelection` tinyint(1) NOT NULL DEFAULT 0,
  `CoverImageKey` char(40) DEFAULT NULL,
  `UpdatedAt` timestamp NOT NULL DEFAULT current_timestamp() ON UPDATE current_timestamp(),
  `CreatedAt` timestamp NOT NULL DEFAULT current_timestamp(),
  PRIMARY KEY (`EbookId`),
  UNIQUE KEY `Identifier` (`Identifier`),
  KEY `EbookCreatedAt` (`EbookCreatedAt`),
  KEY `DownloadsPast30Days_EbookCreatedAt` (`DownloadsPast30Days`,`EbookCreatedAt`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_520_ci;
